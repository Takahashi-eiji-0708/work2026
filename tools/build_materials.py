def build_transcript():
    doc = new_document()
    para(doc, "商談文字起こし：みらい商事 初回訪問", size=16, bold=True)
    para(doc, DISCLAIMER, size=8.5)
    for speaker, text in TRANSCRIPT:
        if speaker:
            para(doc, f"{speaker}：{text}")
        else:
            para(doc, text, size=9.5)
    doc.save(OUT / "03_商談文字起こし_初回訪問.docx")
    # アプリ演習でも使えるようにテキスト版も出力する
    lines = [f"{s}：{t}" if s else t for s, t in TRANSCRIPT]
    (OUT / "03_商談文字起こし_初回訪問.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


