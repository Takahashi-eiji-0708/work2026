    para(doc, "以下は、みらい商事への初回訪問に向けて営業担当者が書き留めたメモです。"
              "このメモを Copilot に貼り付けて「ヒアリングで聞くべき質問を考えて」と依頼しようとしています。")
    heading(doc, "メモ本文", 1)
