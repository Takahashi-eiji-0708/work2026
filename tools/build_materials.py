def build_training_records():
    rng = random.Random(20261006)
    wb = Workbook()
    ws = wb.active
    ws.title = "研修実績"
    headers = ["研修ID", "実施年度", "実施月", "顧客業種", "顧客規模", "コース名", "カテゴリ", "実施形式",
               "現場課題演習", "日数", "受講者数", "満足度", "理解度テスト平均", "3か月後実践率", "受講料総額", "担当営業"]
    ws.append(headers)
    rows = []
    for i in range(1, 161):
        year = rng.choice([2023, 2024, 2025])
        course, cat = rng.choice(COURSES)
        ind = rng.choice(INDUSTRIES)
        fmt = rng.choice(["集合", "集合", "オンライン"])
        custom = "あり" if rng.random() < (0.45 if cat in ("DX", "データ活用") else 0.2) else "なし"
        if cat in ("DX", "データ活用") and year == 2025:
            custom = "あり" if rng.random() < 0.65 else custom
        days = {"Python入門": 2, "新任管理職研修": 2}.get(course, rng.choice([1, 1, 2]))
        people = rng.randint(8, 30)
        sat = 3.85 + (0.2 if fmt == "集合" else -0.15) + (0.35 if custom == "あり" else 0) + rng.uniform(-0.3, 0.3)
        if ind == "製造業" and cat in ("DX", "データ活用") and custom == "なし":
            sat -= 0.2
        test = 68 + (6 if fmt == "集合" else 0) + (5 if custom == "あり" else 0) + rng.uniform(-8, 8)
        practice = 35 + (22 if custom == "あり" else 0) + (5 if fmt == "集合" else 0) + rng.uniform(-10, 10)
        fee = people * days * rng.choice([28000, 30000, 32000, 35000]) + (400000 if custom == "あり" else 0)
        rows.append([f"T{year % 100}{i:03d}", year, rng.randint(1, 12), ind, rng.choice(SIZES), course, cat, fmt,
                     custom, days, people, round(min(sat, 5.0), 1), round(min(test, 100)), round(max(min(practice, 95), 5)),
                     fee, rng.choice(SALES)])
    rows.sort(key=lambda r: (r[1], r[2]))
    # 表記ゆれ・欠損をわざと混ぜる（演習9で Copilot にデータ確認させる）
    for idx in (7, 41, 96):
        rows[idx][3] = "製造"
    rows[58][3] = "情報通信"
    rows[120][11] = None
    for r in rows:
        ws.append(r)
    _style_sheet(ws, [9, 9, 7, 12, 11, 24, 12, 9, 12, 6, 9, 8, 14, 12, 12, 9])
    for row in ws.iter_rows(min_row=2, min_col=15, max_col=15):
        row[0].number_format = "#,##0"
    tab = Table(displayName="研修実績", ref=f"A1:{get_column_letter(len(headers))}{len(rows) + 1}")
    tab.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True)
    ws.add_table(tab)

