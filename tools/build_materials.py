def build_training_records():
    rng = random.Random(20261006)
    wb = Workbook()
    ws = wb.active
    ws.title = "研修実績"
    headers = ["研修ID", "実施年度", "実施月", "顧客業種", "顧客規模", "対象職種", "コース名", "カテゴリ", "実施形式",
               "事前診断", "事後フォロー", "日数", "受講者数", "満足度", "理解度テスト平均", "1か月後活用率",
               "受講料総額", "担当営業"]
    ws.append(headers)
    rows = []
    for i in range(1, 161):
        year = rng.choice([2023, 2024, 2025])
        course, cat = rng.choice(COURSES)
        if cat == "生成AI" and year == 2023 and rng.random() < 0.6:  # 生成AI研修は2024年度から増加
            year = rng.choice([2024, 2025])
        ind = rng.choice(INDUSTRIES)
        target = "営業職" if course in ("営業のための生成AI実践", "提案型営業スキル") else rng.choice(TARGETS)
        fmt = rng.choice(["集合", "集合", "オンライン"])
        diag = "あり" if rng.random() < 0.4 else "なし"
        follow = "あり" if rng.random() < 0.4 else "なし"
        days = {"新任管理職研修": 2}.get(course, rng.choice([1, 2, 2]))
        people = rng.randint(8, 30)
        sat = 3.85 + (0.2 if fmt == "集合" else -0.15) + (0.2 if diag == "あり" else 0) + rng.uniform(-0.3, 0.3)
        test = 68 + (6 if fmt == "集合" else 0) + (5 if diag == "あり" else 0) + rng.uniform(-8, 8)
        usage = 38 + (18 if follow == "あり" else 0) + (5 if diag == "あり" else 0) + (4 if fmt == "集合" else 0) \
            + rng.uniform(-10, 10)
        fee = people * days * rng.choice([12500, 15000, 17500]) + (200000 if diag == "あり" else 0) \
            + (200000 if follow == "あり" else 0)
        rows.append([f"T{year % 100}{i:03d}", year, rng.randint(1, 12), ind, rng.choice(SIZES), target, course, cat, fmt,
                     diag, follow, days, people, round(min(sat, 5.0), 1), round(min(test, 100)),
                     round(max(min(usage, 95), 5)), fee, rng.choice(SALES)])
    rows.sort(key=lambda r: (r[1], r[2]))
    # 表記ゆれ・欠損をわざと混ぜる（演習9で Copilot にデータ確認させる）
    for idx in (7, 41, 96):
        rows[idx][3] = "卸売"
    rows[58][3] = "情報通信"
    rows[120][13] = None
    for r in rows:
        ws.append(r)
    _style_sheet(ws, [9, 9, 7, 12, 11, 9, 24, 11, 9, 9, 11, 6, 9, 8, 14, 12, 12, 9])
    for row in ws.iter_rows(min_row=2, min_col=17, max_col=17):
        row[0].number_format = "#,##0"
    tab = Table(displayName="研修実績", ref=f"A1:{get_column_letter(len(headers))}{len(rows) + 1}")
    tab.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True)
    ws.add_table(tab)

