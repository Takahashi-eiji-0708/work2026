"""各スライドの直後に差し込むミニ演習（問題スライドと解答スライド）。

MINIS は「直前のスライドのタイトル」→「差し込むスライドを作る関数のリスト」。
問題と解答は docs/09_ミニ演習集.md と同じ内容にしておくこと。
"""
from slide_lib import BLUE, GRAY, LIGHT, NAVY, ORANGE, ORANGE_PALE, PALE, TEXT, WHITE, W, X0, Slide, para, ps

GREEN_PALE, AMBER_PALE, RED_PALE = "E3F2E8", "FFF4D6", "FBE3E0"
CODE_FILL = "F4F4F4"
TOP = 1650000
BOTTOM_LIMIT = 5450000


def _header(s, label, minutes, lead):
    s.box(X0, 1030000, 1500000, 420000, para(f"ミニ演習 {label}", size=1250, bold=True, color=WHITE, align="ctr"),
          fill=ORANGE, prst="roundRect", anchor="ctr", inset=(0, 0, 0, 0))
    s.box(X0 + 1600000, 1030000, 900000, 420000, para(minutes, size=1200, bold=True, color=ORANGE, align="ctr"),
          fill=ORANGE_PALE, prst="roundRect", anchor="ctr", inset=(0, 0, 0, 0))
    s.text(X0 + 2650000, 1030000, W - 2650000, 420000, para(lead, size=1250, bold=True, color=NAVY, line=110000), anchor="ctr")


def _row_h(n, top=TOP, bottom=BOTTOM_LIMIT, header=400000, maxh=620000):
    return [header] + [min(maxh, int((bottom - top - header) / n))] * n


def quiz(label, minutes, title, lead, headers, rows, widths, note="", aligns=None, top=TOP):
    """表形式の問題スライド。最後の列は受講者が記入する空欄。"""
    def make():
        s = Slide("content", f"ミニ演習 {label}：{title}")
        _header(s, label, minutes, lead)
        s.table(X0, top, widths, [headers] + rows, row_h=_row_h(len(rows), top=top), size=1150, aligns=aligns)
        if note:
            s.text(X0, 5550000, W, 450000, para(note, size=1100, color=GRAY, line=110000))
        return s
    return make


def answer(label, title, headers, rows, widths, note="", fills=None, aligns=None):
    """解答スライド。"""
    def make():
        s = Slide("content", f"ミニ演習 {label}　解答：{title}")
        top = 1030000
        s.table(X0, top, widths, [headers] + rows, row_h=_row_h(len(rows), top=top, bottom=5000000, maxh=640000),
                size=1150, fills=fills or {}, aligns=aligns)
        if note:
            s.box(X0, 5100000, W, 900000, para(note, size=1200, line=115000, accent=NAVY),
                  fill=LIGHT, prst="roundRect", anchor="ctr", inset=(220000, 45720, 220000, 45720))
        return s
    return make


def checklist(label, minutes, title, lead, items, note=""):
    """確認チェックリスト形式（解答なし）。"""
    def make():
        s = Slide("content", f"ミニ演習 {label}：{title}")
        _header(s, label, minutes, lead)
        rows = [["No", "確認すること", "結果"]] + [[str(i + 1), t, "☐ できた　☐ できない"] for i, t in enumerate(items)]
        s.table(X0, TOP, [600000, W - 3000000, 2400000], rows, row_h=_row_h(len(items)), size=1150,
                aligns=["ctr", "l", "ctr"])
        if note:
            s.box(X0, 5550000, W, 480000, para(note, size=1100, line=110000),
                  fill=ORANGE_PALE, prst="roundRect", anchor="ctr", inset=(200000, 0, 200000, 0))
        return s
    return make


def _abc_fills(rows, col):
    colors = {"A": GREEN_PALE, "B": AMBER_PALE, "C": RED_PALE, "○": GREEN_PALE, "×": RED_PALE,
              "決定": GREEN_PALE, "未確定": AMBER_PALE}
    out = {}
    for i, r in enumerate(rows):
        for k, c in colors.items():
            if str(r[col]).startswith(k):
                out[(i + 1, col)] = c
    return out


