def insert_minis(slides):
    """スライドのタイトルを見て、直後にミニ演習を差し込む。対応するスライドがない指定はエラーにする。"""
    out, used = [], set()
    for s in slides:
        out.append(s)
        if s.title in MINIS:
            used.add(s.title)
            out.extend(f() for f in MINIS[s.title])
    missing = set(MINIS) - used
    if missing:
        raise ValueError(f"ミニ演習の差し込み先が見つかりません: {missing}")
    return out
